import { generateObject } from "ai";
import { z } from "zod";

import { madridLlm, madridModelId } from "./llm.js";
import type { SelectedPlaceResearch } from "./research-selected-place.js";

const audioGuideSchema = z.object({
  title: z.string().min(1).max(120),
  researchSummary: z.string().min(1).max(700),
  audioScript: z.string().min(200).max(3_500),
});

export type AudioGuide = z.infer<typeof audioGuideSchema>;

export async function generateAudioGuide(research: SelectedPlaceResearch): Promise<AudioGuide> {
  const { object } = await generateObject({
    model: madridLlm.chat(madridModelId),
    schema: audioGuideSchema,
    system: "You write accurate, engaging Spanish audio guides for small historical places in Madrid. You never invent facts.",
    prompt: `Create a concise Spanish deep-research summary and a 90–120 second Spanish audio-guide script for the selected place.
Use only the source material supplied below. Do not infer historical facts, dates, people, architectural styles, or events that the source material does not state. If the material is sparse, say less rather than guessing.
The audio script should be natural to listen to while standing nearby, include an invitation to look around, and not mention that it was generated by AI.

Selected place: ${research.name}
Canonical source: ${research.sourceUrls.join(", ")}
Source material:
${research.sourceMaterial}`,
  });

  return object;
}
